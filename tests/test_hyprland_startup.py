#!/usr/bin/env python3
import importlib.util
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

MODULE_PATH = Path(__file__).resolve().parents[1] / "scripts" / "hyprland-startup.py"
SPEC = importlib.util.spec_from_file_location("hyprland_startup", MODULE_PATH)
hyprland_startup = importlib.util.module_from_spec(SPEC)
assert SPEC.loader is not None
SPEC.loader.exec_module(hyprland_startup)


class HyprlandStartupTests(unittest.TestCase):
    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp_dir.cleanup)
        self.root = Path(self.temp_dir.name)
        self.config_home = self.root / "xdg"
        self.hypr_dir = self.config_home / "hypr"
        self.hypr_dir.mkdir(parents=True)
        self.launcher = self.config_home / "pynix-shell" / "scripts" / "start-shell.sh"
        self.launcher.parent.mkdir(parents=True)
        self.launcher.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
        self.launcher.chmod(0o755)
        self.ipc_helper = self.launcher.with_name("pynix-ipc.sh")
        self.ipc_helper.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
        self.ipc_helper.chmod(0o755)
        self.backups = self.root / "backups"
        self.env_patch = patch.dict(os.environ, {"XDG_CONFIG_HOME": str(self.config_home)})
        self.env_patch.start()
        self.addCleanup(self.env_patch.stop)

    def test_empty_xdg_config_home_uses_home_default(self):
        with patch.dict(os.environ, {"XDG_CONFIG_HOME": ""}):
            self.assertEqual(hyprland_startup.config_home(), Path.home() / ".config")

    def installed_version(self, version=(0, 56)):
        return patch.multiple(
            hyprland_startup.shutil,
            which=lambda name: "/usr/bin/Hyprland" if name == "Hyprland" else None,
        ), patch.object(
            hyprland_startup.subprocess,
            "run",
            return_value=type(
                "Completed",
                (),
                {"stdout": f"Hyprland {version[0]}.{version[1]}.0\n", "stderr": "", "returncode": 0},
            )(),
        )

    def test_format_is_detected_from_contents_not_extension(self):
        self.assertEqual(
            hyprland_startup.detect_format('hl.config({ autogenerated = true })\nhl.on("hyprland.start", function() end)\n'),
            "lua",
        )
        self.assertEqual(
            hyprland_startup.detect_format("exec-once = waybar\nmonitor = ,preferred,auto,1\n"),
            "hyprlang",
        )
        with self.assertRaises(hyprland_startup.IntegrationError):
            hyprland_startup.detect_format("unrecognized configuration content\n")
        with self.assertRaises(hyprland_startup.IntegrationError):
            hyprland_startup.detect_format('hl.config({})\nexec-once = waybar\n')

    def test_lua_config_detection_respects_version_default_and_contents(self):
        config = self.hypr_dir / "hyprland.lua"
        config.write_text('hl.config({ autogenerated = true })\n', encoding="utf-8")
        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            detected_path, fmt, version = hyprland_startup.detect_config()
        self.assertEqual(detected_path, config.resolve())
        self.assertEqual(fmt, "lua")
        self.assertEqual(version, (0, 56))

    def test_fresh_missing_directory_generates_usable_lua_config_and_removes_it_safely(self):
        self.hypr_dir.rmdir()
        which_patch, run_patch = self.installed_version((0, 55))
        with which_patch, run_patch:
            config, fmt, version = hyprland_startup.detect_config()
            self.assertEqual(config, self.hypr_dir / "hyprland.lua")
            self.assertEqual(fmt, "lua")
            self.assertEqual(version, (0, 55))
            self.assertFalse(self.hypr_dir.exists())

            created, digest = hyprland_startup.install(
                config, self.launcher, self.backups, terminal="/usr/bin/foot"
            )
            generated = config.read_text(encoding="utf-8")
            self.assertTrue(created)
            self.assertRegex(digest, r"^[0-9a-f]{64}$")
            self.assertIn(hyprland_startup.GENERATED_BASE_MARKER, generated)
            self.assertIn("-- >>> PYNIX-SHELL MANAGED STARTUP BEGIN >>>", generated)
            self.assertNotIn("# >>> PYNIX-SHELL MANAGED STARTUP BEGIN >>>", generated)
            self.assertIn('hl.bind("SUPER + Q", hl.dsp.exec_cmd("/usr/bin/foot"))', generated)
            self.assertIn("hyprctl dispatch 'hl.dsp.exit()'", generated)
            self.assertIn('hl.on("hyprland.start", function()', generated)
            self.assertIn(str(self.launcher), generated)
            self.assertNotIn(str(Path(__file__).resolve().parents[1]), generated)

            created_again, digest_again = hyprland_startup.install(
                config, self.launcher, self.backups, terminal="/usr/bin/foot"
            )
            self.assertFalse(created_again)
            self.assertEqual(digest_again, digest)
            self.assertEqual(config.read_text(encoding="utf-8"), generated)
            hyprland_startup.remove(config, digest)
        self.assertFalse(config.exists())
        self.assertFalse(self.hypr_dir.exists())

    def test_fresh_legacy_directory_generates_hyprlang_config(self):
        self.hypr_dir.rmdir()
        which_patch, run_patch = self.installed_version((0, 54))
        with which_patch, run_patch:
            config, fmt, _ = hyprland_startup.detect_config()
            self.assertEqual(config, self.hypr_dir / "hyprland.conf")
            self.assertEqual(fmt, "hyprlang")
            created, digest = hyprland_startup.install(
                config, self.launcher, self.backups, terminal="/usr/bin/foot"
            )
            self.assertTrue(created)
            generated = config.read_text(encoding="utf-8")
            self.assertIn("autogenerated=1", generated)
            self.assertIn("$pynix_terminal = /usr/bin/foot", generated)
            self.assertIn("bind = SUPER, Q, exec, $pynix_terminal", generated)
            self.assertIn("bind = SUPER, M, exit", generated)
            self.assertIn(f"exec-once = {self.launcher}", generated)
            hyprland_startup.remove(config, digest)
        self.assertFalse(config.exists())

    def test_helper_cli_creates_repeats_and_uninstalls_a_fresh_configuration(self):
        self.hypr_dir.rmdir()
        mock_bin = self.root / "mock-bin"
        mock_bin.mkdir()
        hyprland = mock_bin / "Hyprland"
        hyprland.write_text("#!/bin/sh\nprintf 'Hyprland 0.55.1\\n'\n", encoding="utf-8")
        hyprland.chmod(0o755)
        config = self.hypr_dir / "hyprland.lua"
        command = [
            sys.executable,
            str(MODULE_PATH),
            "install",
            "--config",
            str(config),
            "--launcher",
            str(self.launcher),
            "--backup-dir",
            str(self.backups),
            "--terminal",
            "/usr/bin/foot",
        ]
        env = os.environ.copy()
        env["PATH"] = f"{mock_bin}:{env.get('PATH', '')}"
        env["XDG_CONFIG_HOME"] = str(self.config_home)

        first = subprocess.run(command, env=env, capture_output=True, text=True, check=False)
        self.assertEqual(first.returncode, 0, first.stderr)
        self.assertIn("PYNIX_CONFIG_CREATED:1", first.stdout)
        digest = next(
            line.split(":", 1)[1]
            for line in first.stdout.splitlines()
            if line.startswith("PYNIX_GENERATED_BASE_SHA256:")
        )
        self.assertRegex(digest, r"^[0-9a-f]{64}$")

        second = subprocess.run(command, env=env, capture_output=True, text=True, check=False)
        self.assertEqual(second.returncode, 0, second.stderr)
        self.assertIn("PYNIX_CONFIG_CREATED:0", second.stdout)
        self.assertIn(f"PYNIX_GENERATED_BASE_SHA256:{digest}", second.stdout)
        self.assertEqual(config.read_text(encoding="utf-8").count(hyprland_startup.BEGIN), 1)

        removed = subprocess.run(
            [
                sys.executable,
                str(MODULE_PATH),
                "remove",
                "--config",
                str(config),
                "--generated-sha256",
                digest,
            ],
            env=env,
            capture_output=True,
            text=True,
            check=False,
        )
        self.assertEqual(removed.returncode, 0, removed.stderr)
        self.assertFalse(config.exists())
        self.assertFalse(self.hypr_dir.exists())

