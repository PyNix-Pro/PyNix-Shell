    def test_modified_managed_block_is_not_removed(self):
        config = self.hypr_dir / "hyprland.lua"
        config.write_text("hl.config({ autogenerated = true })\n", encoding="utf-8")
        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            hyprland_startup.install(config, self.launcher, self.backups)
        changed = config.read_text(encoding="utf-8").replace(
            f'hl.exec_cmd("{self.launcher}")',
            f'hl.exec_cmd("{self.launcher}")\n    hl.exec_cmd("user-command")',
        )
        config.write_text(changed, encoding="utf-8")
        with self.assertRaisesRegex(hyprland_startup.IntegrationError, "user-edited"):
            hyprland_startup.remove(config)
        self.assertEqual(config.read_text(encoding="utf-8"), changed)

