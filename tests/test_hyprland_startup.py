#!/usr/bin/env python3
import importlib.util
import os
import tempfile
import unittest
from pathlib import Path
from unittest.mock import patch

MODULE_PATH = Path(__file__).resolve().parents[1] / "scripts" / "hyprland-startup.py"
SPEC = importlib.util.spec_from_file_location("hyprland_startup", MODULE_PATH)
hyprland_startup = importlib.util.module_from_spec(SPEC)
assert SPEC.loader is not None
SPEC.loader.exec_module(hyprland_startup)


class HyprlandStartupTests(unittest.TestCase):
    def setUp(self):
        self.temp_dir = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp_dir.cleanup)
        self.root = Path(self.temp_dir.name)
        self.config_home = self.root / "xdg"
        self.hypr_dir = self.config_home / "hypr"
        self.hypr_dir.mkdir(parents=True)
        self.launcher = self.config_home / "pynix-shell" / "scripts" / "start-shell.sh"
        self.launcher.parent.mkdir(parents=True)
        self.launcher.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
        self.launcher.chmod(0o755)
        self.ipc_helper = self.launcher.with_name("pynix-ipc.sh")
        self.ipc_helper.write_text("#!/bin/sh\nexit 0\n", encoding="utf-8")
        self.ipc_helper.chmod(0o755)
        self.backups = self.root / "backups"
        self.env_patch = patch.dict(os.environ, {"XDG_CONFIG_HOME": str(self.config_home)})
        self.env_patch.start()
        self.addCleanup(self.env_patch.stop)

    def test_empty_xdg_config_home_uses_home_default(self):
        with patch.dict(os.environ, {"XDG_CONFIG_HOME": ""}):
            self.assertEqual(hyprland_startup.config_home(), Path.home() / ".config")

    def installed_version(self, version=(0, 56)):
        return patch.multiple(
            hyprland_startup.shutil,
            which=lambda name: "/usr/bin/Hyprland" if name == "Hyprland" else None,
        ), patch.object(
            hyprland_startup.subprocess,
            "run",
            return_value=type(
                "Completed",
                (),
                {"stdout": f"Hyprland {version[0]}.{version[1]}.0\n", "stderr": "", "returncode": 0},
            )(),
        )

    def test_format_is_detected_from_contents_not_extension(self):
        self.assertEqual(
            hyprland_startup.detect_format('hl.config({ autogenerated = true })\nhl.on("hyprland.start", function() end)\n'),
            "lua",
        )
        self.assertEqual(
            hyprland_startup.detect_format("exec-once = waybar\nmonitor = ,preferred,auto,1\n"),
            "hyprlang",
        )
        with self.assertRaises(hyprland_startup.IntegrationError):
            hyprland_startup.detect_format("unrecognized configuration content\n")
        with self.assertRaises(hyprland_startup.IntegrationError):
            hyprland_startup.detect_format('hl.config({})\nexec-once = waybar\n')

    def test_lua_config_detection_respects_version_default_and_contents(self):
        config = self.hypr_dir / "hyprland.lua"
        config.write_text('hl.config({ autogenerated = true })\n', encoding="utf-8")
        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            detected_path, fmt, version = hyprland_startup.detect_config()
        self.assertEqual(detected_path, config.resolve())
        self.assertEqual(fmt, "lua")
        self.assertEqual(version, (0, 56))

    def test_multiple_config_candidates_use_version_default_then_inspect_contents(self):
        lua_config = self.hypr_dir / "hyprland.lua"
        old_config = self.hypr_dir / "hyprland.conf"
        lua_config.write_text('hl.config({ autogenerated = true })\n', encoding="utf-8")
        old_config.write_text("exec-once = waybar\n", encoding="utf-8")

        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            path, fmt, _ = hyprland_startup.detect_config()
        self.assertEqual(path, lua_config.resolve())
        self.assertEqual(fmt, "lua")

        which_patch, run_patch = self.installed_version((0, 54))
        with which_patch, run_patch:
            path, fmt, _ = hyprland_startup.detect_config()
        self.assertEqual(path, old_config.resolve())
        self.assertEqual(fmt, "hyprlang")

    def test_wrong_extension_is_still_classified_by_content(self):
        config = self.hypr_dir / "hyprland.conf"
        config.write_text('hl.config({ autogenerated = true })\n', encoding="utf-8")
        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            detected_path, fmt, _ = hyprland_startup.detect_config(config)
        self.assertEqual(detected_path, config.resolve())
        self.assertEqual(fmt, "lua")

    def test_hyprlang_compatibility_on_legacy_version(self):
        config = self.hypr_dir / "hyprland.lua"
        config.write_text("exec-once = waybar\n", encoding="utf-8")
        which_patch, run_patch = self.installed_version((0, 54))
        with which_patch, run_patch:
            path, fmt, version = hyprland_startup.detect_config(config)
        self.assertEqual(path, config.resolve())
        self.assertEqual(fmt, "hyprlang")
        self.assertEqual(version, (0, 54))

    def test_format_version_mismatch_is_rejected(self):
        config = self.hypr_dir / "hyprland.lua"
        config.write_text("hl.config({ autogenerated = true })\n", encoding="utf-8")
        which_patch, run_patch = self.installed_version((0, 54))
        with which_patch, run_patch:
            with self.assertRaisesRegex(hyprland_startup.IntegrationError, "predates Lua"):
                hyprland_startup.detect_config(config)

    def test_lua_managed_startup_is_idempotent_and_removes_only_itself(self):
        original = "# user's settings\nhl.config({ autogenerated = true })\n"
        config = self.hypr_dir / "config.without-lua-extension"
        config.write_text(original, encoding="utf-8")
        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            hyprland_startup.install(config, self.launcher, self.backups)
            integrated = config.read_text(encoding="utf-8")
            self.assertEqual(integrated.count(hyprland_startup.BEGIN), 1)
            self.assertIn('hl.on("hyprland.start", function()', integrated)
            self.assertIn(str(self.launcher), integrated)
            self.assertNotIn(str(Path(__file__).resolve().parents[1]), integrated)
            backup_files = list(self.backups.glob("*.backup"))
            self.assertEqual(len(backup_files), 1)
            self.assertEqual(backup_files[0].read_text(encoding="utf-8"), original)
            hyprland_startup.install(config, self.launcher, self.backups)
            self.assertEqual(config.read_text(encoding="utf-8"), integrated)
            self.assertEqual(len(list(self.backups.glob("*.backup"))), 1)
            hyprland_startup.remove(config)
        self.assertEqual(config.read_text(encoding="utf-8"), original)

    def test_hyprlang_block_and_exact_round_trip_without_final_newline(self):
        original = "general {\n  gaps_in = 4\n}"
        config = self.hypr_dir / "hyprland.lua"
        config.write_text(original, encoding="utf-8")
        which_patch, run_patch = self.installed_version((0, 54))
        with which_patch, run_patch:
            hyprland_startup.install(config, self.launcher, self.backups)
            integrated = config.read_text(encoding="utf-8")
            self.assertIn("exec-once =", integrated)
            self.assertEqual(integrated.count(hyprland_startup.BEGIN), 1)
            hyprland_startup.remove(config)
        self.assertEqual(config.read_text(encoding="utf-8"), original)

    def test_optional_lua_keybindings_are_added_idempotently_and_removed_exactly(self):
        original = "hl.config({ autogenerated = true })\n"
        config = self.hypr_dir / "hyprland.lua"
        config.write_text(original, encoding="utf-8")
        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            hyprland_startup.install(config, self.launcher, self.backups, keybindings=True)
            integrated = config.read_text(encoding="utf-8")
            self.assertIn("# pynix-keybindings: 1", integrated)
            self.assertIn('hl.bind("SUPER + F10", hl.dsp.exec_cmd(', integrated)
            self.assertIn("open-control-center", integrated)
            self.assertIn("close-control-center", integrated)
            self.assertIn("open-theme-switcher", integrated)
            self.assertEqual(integrated.count(hyprland_startup.BEGIN), 1)
            hyprland_startup.install(config, self.launcher, self.backups, keybindings=True)
            self.assertEqual(config.read_text(encoding="utf-8"), integrated)
            hyprland_startup.remove(config)
        self.assertEqual(config.read_text(encoding="utf-8"), original)

    def test_optional_hyprlang_keybindings_use_supported_bind_syntax(self):
        config = self.hypr_dir / "hyprland.conf"
        config.write_text("exec-once = waybar\n", encoding="utf-8")
        which_patch, run_patch = self.installed_version((0, 54))
        with which_patch, run_patch:
            hyprland_startup.install(config, self.launcher, self.backups, keybindings=True)
            integrated = config.read_text(encoding="utf-8")
            self.assertIn("bind = SUPER, F10, exec,", integrated)
            self.assertIn("bind = SUPER_SHIFT, F10, exec,", integrated)
            self.assertIn("bind = SUPER, F11, exec,", integrated)
            self.assertIn("open-launcher", integrated)
            hyprland_startup.remove(config)
        self.assertEqual(config.read_text(encoding="utf-8"), "exec-once = waybar\n")

    def test_keybindings_refuse_missing_ipc_helper(self):
        config = self.hypr_dir / "hyprland.lua"
        config.write_text("hl.config({ autogenerated = true })\n", encoding="utf-8")
        self.ipc_helper.unlink()
        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            with self.assertRaisesRegex(hyprland_startup.IntegrationError, "IPC command helper"):
                hyprland_startup.install(config, self.launcher, self.backups, keybindings=True)

    def test_invalid_launcher_and_ambiguous_duplicate_markers_are_refused(self):
        config = self.hypr_dir / "hyprland.lua"
        config.write_text("hl.config({ autogenerated = true })\n", encoding="utf-8")
        missing_launcher = self.root / "missing-launcher"
        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            with self.assertRaisesRegex(hyprland_startup.IntegrationError, "missing or not executable"):
                hyprland_startup.install(config, missing_launcher, self.backups)

        config.write_text(
            f"hl.config({{}})\n{hyprland_startup.BEGIN}\n{hyprland_startup.END}\n"
            f"{hyprland_startup.BEGIN}\n{hyprland_startup.END}\n",
            encoding="utf-8",
        )
        with self.assertRaisesRegex(hyprland_startup.IntegrationError, "duplicated"):
            hyprland_startup.remove(config)

    def test_modified_managed_block_is_not_removed(self):
        config = self.hypr_dir / "hyprland.lua"
        config.write_text("hl.config({ autogenerated = true })\n", encoding="utf-8")
        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            hyprland_startup.install(config, self.launcher, self.backups)
        changed = config.read_text(encoding="utf-8").replace(
            f'hl.exec_cmd("{self.launcher}")',
            f'hl.exec_cmd("{self.launcher}")\n    hl.exec_cmd("user-command")',
        )
        config.write_text(changed, encoding="utf-8")
        with self.assertRaisesRegex(hyprland_startup.IntegrationError, "user-edited"):
            hyprland_startup.remove(config)
        self.assertEqual(config.read_text(encoding="utf-8"), changed)

    def test_config_outside_xdg_hypr_is_refused(self):
        outside = self.root / "other.conf"
        outside.write_text("exec-once = waybar\n", encoding="utf-8")
        with self.assertRaisesRegex(hyprland_startup.IntegrationError, "outside"):
            hyprland_startup.validate_config_location(outside)

    def test_symlinked_config_is_refused(self):
        outside = self.root / "outside.conf"
        outside.write_text("exec-once = waybar\n", encoding="utf-8")
        link = self.hypr_dir / "hyprland.conf"
        link.symlink_to(outside)
        with self.assertRaisesRegex(hyprland_startup.IntegrationError, "symlinked"):
            hyprland_startup.validate_config_location(link)


if __name__ == "__main__":
    unittest.main()
