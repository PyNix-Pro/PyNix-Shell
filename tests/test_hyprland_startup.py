    def test_existing_lua_and_legacy_configs_are_selected_by_version_and_contents(self):
        lua_config = self.hypr_dir / "hyprland.lua"
        legacy_config = self.hypr_dir / "hyprland.conf"
        lua_config.write_text("hl.config({ autogenerated = true })\n", encoding="utf-8")
        legacy_config.write_text("exec-once = waybar\n", encoding="utf-8")
        with patch.dict(os.environ, {"XDG_CONFIG_HOME": str(self.config_home)}):
            which_patch, run_patch = self.installed_version((0, 55))
            with which_patch, run_patch:
                self.assertEqual(hyprland_startup.detect_config()[:2], (lua_config, "lua"))
            which_patch, run_patch = self.installed_version((0, 54))
            with which_patch, run_patch:
                self.assertEqual(hyprland_startup.detect_config()[:2], (legacy_config, "hyprlang"))
        self.assertEqual(lua_config.read_text(encoding="utf-8"), "hl.config({ autogenerated = true })\n")
        self.assertEqual(legacy_config.read_text(encoding="utf-8"), "exec-once = waybar\n")

    def test_generated_config_preserves_changes_on_uninstall(self):
        self.hypr_dir.rmdir()
        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            config, _, _ = hyprland_startup.detect_config()
            created, digest = hyprland_startup.install(
                config, self.launcher, self.backups, terminal="/usr/bin/foot"
            )
            self.assertTrue(created)
            config.write_text(config.read_text(encoding="utf-8") + "-- user change\n", encoding="utf-8")
            created_again, changed_digest = hyprland_startup.install(
                config, self.launcher, self.backups, terminal="/usr/bin/foot"
            )
            self.assertFalse(created_again)
            self.assertNotEqual(changed_digest, digest)
            hyprland_startup.remove(config, digest)
        self.assertTrue(config.exists())
        remaining = config.read_text(encoding="utf-8")
        self.assertIn(hyprland_startup.GENERATED_BASE_MARKER, remaining)
        self.assertIn("-- user change", remaining)
        self.assertNotIn(hyprland_startup.BEGIN, remaining)

    def test_malformed_existing_config_is_not_replaced(self):
        config = self.hypr_dir / "hyprland.lua"
        original = "this is not recognized as a Hyprland config\n"
        config.write_text(original, encoding="utf-8")
        which_patch, run_patch = self.installed_version()
        with which_patch, run_patch:
            with self.assertRaisesRegex(hyprland_startup.IntegrationError, "format could not be identified"):
                hyprland_startup.detect_config()
        self.assertEqual(config.read_text(encoding="utf-8"), original)

    def test_unbalanced_lua_and_hyprlang_configs_are_refused_without_edit(self):
        cases = (
            ("hyprland.lua", "hl.config({ general = { gaps_in = 5 })\n", (0, 55)),
            ("hyprland.conf", "general {\n  gaps_in = 5\n", (0, 54)),
        )
        for filename, original, version in cases:
            config = self.hypr_dir / filename
            config.write_text(original, encoding="utf-8")
            which_patch, run_patch = self.installed_version(version)
            with which_patch, run_patch:
                with self.assertRaisesRegex(hyprland_startup.IntegrationError, "delimiter"):
                    hyprland_startup.detect_config(config)
            self.assertEqual(config.read_text(encoding="utf-8"), original)
            config.unlink()

